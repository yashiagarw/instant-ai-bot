// Writes docs/hindi-review.md: every machine-drafted Hindi UI text of the customer site (src/i18n/messages/site.hi.json)
// beside its English, for the team's Hindi speaker to check (Phase 5.5).   pnpm hindi:review   (from apps/web)
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const read = (f) => JSON.parse(readFileSync(path.join(here, "../src/i18n/messages", f), "utf8"));
const flat = (o, p = "") =>
  Object.entries(o).flatMap(([k, v]) => (typeof v === "string" ? [[p + k, v]] : flat(v, `${p}${k}.`)));
const en = Object.fromEntries(flat(read("site.en.json")));
const hi = flat(read("site.hi.json"));
const cell = (s) => s.replace(/\|/g, "\\|");
const rows = hi.map(([k, v]) => `| \`${k}\` | ${cell(en[k])} | ${cell(v)} | |`);
const out = `# Hindi UI text to review (Phase 5.5)

Generated by \`apps/web/scripts/hindi-review.mjs\` (\`cd apps/web && pnpm hindi:review\`) from
\`apps/web/src/i18n/messages/site.hi.json\`. **Every Hindi text below is a machine draft.** Please check each one, fix it
in \`site.hi.json\` (keep the \`{placeholders}\` and the \`{count, plural, …}\` form), tick the last column and re-run the
script. The mechanic app's Hindi (\`m.hi.json\`, ${Object.keys(read("m.hi.json").m).length} texts) is unchanged from
Phase 5.3 and is not listed.

## Never machine-translated (shown in English until reviewed Hindi exists)

These stay English on the Hindi pages, marked \`lang="en"\` for screen readers:

- **Safety alerts** (the red banner) and the **roadside / towing verdict**: 978 safety rules in the published dataset,
  0 with Hindi. The model has no Hindi field for them yet.
- **Safety tips** (\`data/review/safety_tips.yaml\`): no Hindi.
- **The footer's emergency line** ("In an emergency … call 112").
- **Fault names**: the reviewed Hindi name is the shortest *approved* Devanagari customer phrase of the fault
  (\`service.hindi_names\`). Published dataset: **21 of 972 faults** have one (the 63 counted before are the same 21
  faults in each of the 3 dataset versions). By category: ac 2, battery 3, brakes 4, clutch 3, cooling 3,
  not_starting 2, self_start 2, tyre 2; every other category has none.
- **Questions and answer options**: 781 questions and 2,984 options in the published flows, 0 with \`text_hi\` /
  \`label_hi\`.
- **Engine and dataset text** on the result: explanations, evidence, steps, what you can do, picture captions, costs
  shown as text, "If this doesn't fix it", the confidence reason.
- **Parts section and photo findings** on the result: shared with the English-only /parts and request pages.
- **Problem tiles and emergency topics**: their Hindi labels come from the database (\`problem_groups.label_hi\`);
  4 of 22 are marked reviewed (Admin → Knowledge).
- **API error messages** (e.g. "Too many requests …") come from the backend in English.

## Machine-drafted UI text (${rows.length})

| Key | English | Hindi (draft) | Checked |
|---|---|---|---|
${rows.join("\n")}
`;
writeFileSync(path.join(here, "../../../docs/hindi-review.md"), out);
console.log(`docs/hindi-review.md: ${rows.length} texts`);

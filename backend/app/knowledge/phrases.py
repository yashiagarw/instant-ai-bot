"""Reviewed extra customer phrases (data/review/phrases/*.yaml) -> customer_phrases (source drafted).

The datasets' CUSTOMER ON AI column gives most phrases; these files add the ways customers also say it (Hinglish,
common misspellings, Hindi) found missing in the evaluation's dev split. Only entries with status approved load.
They are never held out (they are not evaluation cases) and become searchable after `embeddings sync`.

    uv run python -m app.knowledge.phrases draft   # spelling_variants.yaml -> spellings.yaml (generated phrases)
    uv run python -m app.knowledge.phrases check   # validate the files against the database
    uv run python -m app.knowledge.phrases load    # replace all drafted phrases with the approved entries

File format (one file per category):

    category: brakes
    reviewed_by: claude_code (auto, pending mechanic sign-off)
    phrases:
    - fault: F11-BR-04
      status: approved
      language: hinglish        # en / hinglish / hi
      text: brake pedal neeche tak chala jata hai
      english_gloss: the brake pedal goes all the way down
      why: dev-split misses used "pedal neeche"   # optional note for the reviewer
"""

import argparse
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

import yaml
from sqlalchemy import delete, select
from sqlalchemy.orm import Session

from app.enums import ReviewStatus
from app.knowledge.models import CustomerPhrase, DatasetVersion, Fault, PhraseLanguage, PhraseSource
from app.knowledge.questions.inputs import target_version

PHRASES_DIR = Path(__file__).resolve().parents[3] / "data" / "review" / "phrases"
SPELLINGS_HEADER = """\
# GENERATED by `python -m app.knowledge.phrases draft` from spelling_variants.yaml: do not edit by hand (edit the
# variants file and run draft again). Each phrase is an approved dataset phrase of the same fault with one word spelled
# the way customers also write it. Texts equal to a held-out evaluation phrase are never generated.
"""


class PhraseFileError(ValueError):
    pass


@dataclass
class PhraseReport:
    files: int = 0
    loaded: int = 0
    skipped: list[str] = field(default_factory=list)  # not approved
    by_language: dict[str, int] = field(default_factory=dict)


def read_all(directory: Path = PHRASES_DIR) -> list[tuple[Path, dict]]:
    """Phrase files (every *.yaml except the spelling map)."""
    return [
        (p, yaml.safe_load(p.read_text(encoding="utf-8")) or {})
        for p in sorted(directory.glob("*.yaml"))
        if p.name != "spelling_variants.yaml"
    ]


def draft_spellings(session: Session, directory: Path = PHRASES_DIR) -> tuple[Path, int]:
    """One phrase per (fault, variant spelling): the fault's shortest approved dataset phrase that has the word."""
    spec = yaml.safe_load((directory / "spelling_variants.yaml").read_text(encoding="utf-8")) or {}
    version = target_version(session)
    rows = session.execute(
        select(Fault.fault_key, CustomerPhrase.text, CustomerPhrase.language)
        .join(Fault, Fault.id == CustomerPhrase.fault_id)
        .where(
            Fault.dataset_version_id == version.id,
            CustomerPhrase.source == PhraseSource.dataset,
            CustomerPhrase.status == ReviewStatus.approved,
            CustomerPhrase.held_out.is_(False),
        )
        .order_by(Fault.fault_key, CustomerPhrase.id)
    ).all()
    held_out = {
        t.lower().strip()
        for (t,) in session.execute(select(CustomerPhrase.text).where(CustomerPhrase.held_out.is_(True)))
    }
    existing = {(k, t.lower().strip()) for k, t, _ in rows}
    best: dict[tuple[str, str], tuple[str, str, str]] = {}  # (fault, variant) -> (text, language, word)
    for word, variants in (spec.get("variants") or {}).items():
        pattern = re.compile(rf"(?<![a-z0-9]){re.escape(word)}(?![a-z0-9])", re.I)
        for key, text, lang in rows:
            if not pattern.search(text):
                continue
            for v in variants:
                new = pattern.sub(v, text, count=1)
                low = new.lower().strip()
                if low in held_out or (key, low) in existing:
                    continue
                if (key, v) not in best or len(new) < len(best[(key, v)][0]):
                    best[(key, v)] = (new, str(lang) if str(lang) in ("en", "hinglish") else "hinglish", word)
    phrases = [
        {
            "fault": key,
            "status": spec.get("status", "draft"),
            "language": lang,  # the source phrase's language (an English sentence stays English)
            "text": text,
            "why": f"spelling of '{word}'",
        }
        for (key, variant), (text, lang, word) in sorted(best.items())
    ]
    doc = {"category": "all", "reviewed_by": spec.get("reviewed_by", ""), "phrases": phrases}
    path = directory / "spellings.yaml"
    path.write_text(
        SPELLINGS_HEADER + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=110), encoding="utf-8"
    )
    return path, len(phrases)


def validate(docs: list[tuple[Path, dict]], keys: set[str]) -> None:
    seen = set()
    languages = {x.value for x in PhraseLanguage} - {"unknown"}
    for path, doc in docs:
        for i, p in enumerate(doc.get("phrases") or []):
            where = f"{path.name} #{i + 1}"
            if p.get("fault") not in keys:
                raise PhraseFileError(f"{where}: unknown fault {p.get('fault')}")
            if p.get("language") not in languages:
                raise PhraseFileError(f"{where}: language must be one of {sorted(languages)}")
            text = (p.get("text") or "").strip()
            if len(text) < 3:
                raise PhraseFileError(f"{where}: empty text")
            k = (p["fault"], text.lower())
            if k in seen:
                raise PhraseFileError(f"{where}: duplicate phrase for {p['fault']}")
            seen.add(k)


def load(session: Session, docs: list[tuple[Path, dict]], version: DatasetVersion | None = None) -> PhraseReport:
    version = version or target_version(session)
    faults = dict(
        session.execute(select(Fault.fault_key, Fault.id).where(Fault.dataset_version_id == version.id)).all()
    )
    validate(docs, set(faults))
    session.execute(
        delete(CustomerPhrase).where(
            CustomerPhrase.source == PhraseSource.drafted, CustomerPhrase.fault_id.in_(faults.values())
        )
    )
    report = PhraseReport(files=len(docs))
    for _path, doc in docs:
        for p in doc.get("phrases") or []:
            if p.get("status") != "approved":
                report.skipped.append(f"{p['fault']}: {p['text']}")
                continue
            session.add(
                CustomerPhrase(
                    fault_id=faults[p["fault"]],
                    text=p["text"].strip(),
                    english_gloss=(p.get("english_gloss") or "").strip() or None,
                    language=p["language"],
                    is_synthetic=True,
                    source=PhraseSource.drafted,
                    status=ReviewStatus.approved,
                    held_out=False,
                    reviewed_by=(doc.get("reviewed_by") or "").strip() or None,
                )
            )
            report.loaded += 1
            report.by_language[p["language"]] = report.by_language.get(p["language"], 0) + 1
    session.flush()
    return report


def main(argv: list[str] | None = None) -> int:
    from app.config import get_settings
    from app.db import make_engine, make_session_factory

    ap = argparse.ArgumentParser(prog="python -m app.knowledge.phrases")
    ap.add_argument("command", choices=["draft", "check", "load"])
    ap.add_argument("--dir", type=Path, default=PHRASES_DIR)
    args = ap.parse_args(argv)
    with make_session_factory(make_engine(get_settings().database_url))() as session:
        if args.command == "draft":
            path, n = draft_spellings(session, args.dir)
            print(f"{n} spelling phrases written to {path}")
            return 0
        docs = read_all(args.dir)
        if args.command == "check":
            version = target_version(session)
            validate(docs, set(session.scalars(select(Fault.fault_key).where(Fault.dataset_version_id == version.id))))
            print(f"OK: {sum(len(d.get('phrases') or []) for _, d in docs)} phrases in {len(docs)} files")
            return 0
        report = load(session, docs)
        session.commit()
    print(
        f"{report.loaded} phrases loaded from {report.files} files {report.by_language}; "
        f"{len(report.skipped)} not approved"
    )
    print("Now run: uv run python -m app.knowledge.embeddings sync")
    return 0


if __name__ == "__main__":
    sys.exit(main())
